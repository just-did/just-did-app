四、局域网 HTTP 通信说明

本应用支持通过局域网 HTTP 与电脑端通信。

HTTP 通信不具备 HTTPS 所提供的传输加密和服务器身份认证能力。在使用 HTTP 地址时，同一网络内的恶意设备、被控制的路由器或其他网络攻击者可能监听或篡改通信内容。

相关风险可能包括：

- 工作记录正文被读取；
- 工作日期和时间被获知；
- 日报内容被篡改；
- 应用连接到错误或被冒充的电脑端；
- 推送结果被伪造。

为降低风险，请您：

- 只在可信的家庭或办公局域网中使用；
- 不要在公共 Wi-Fi 环境中推送敏感工作内容；
- 只扫描由您本人电脑端生成的二维码；
- 发现地址或连接状态异常时停止同步；
- 避免在工作记录中填写密码、金融账户等敏感信息。

您主动点击推送或拉取，表示您要求本应用与二维码指定的电脑端进行相应数据传输。

